// Generates deterministic glyph advance tables for the carousel layout engine.
// Run: pnpm --filter @tapkit/core gen:fonts
import * as fontkit from "fontkit";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const fontDir = (pkg) => path.dirname(require.resolve(`@expo-google-fonts/${pkg}/package.json`));

export const FONTS = {
  "inter-400": ["inter", "400Regular/Inter_400Regular.ttf"],
  "inter-600": ["inter", "600SemiBold/Inter_600SemiBold.ttf"],
  "inter-800": ["inter", "800ExtraBold/Inter_800ExtraBold.ttf"],
  "dmserif-400": ["dm-serif-display", "400Regular/DMSerifDisplay_400Regular.ttf"],
  "grotesk-500": ["space-grotesk", "500Medium/SpaceGrotesk_500Medium.ttf"],
  "grotesk-700": ["space-grotesk", "700Bold/SpaceGrotesk_700Bold.ttf"],
};

const EXTRA = "‘’“”–—•…✓→←×€£";
const chars = [];
for (let c = 32; c < 256; c++) if (c < 127 || c > 160) chars.push(String.fromCharCode(c));
for (const ch of EXTRA) chars.push(ch);

const out = {};
for (const [key, [pkg, file]] of Object.entries(FONTS)) {
  const font = fontkit.openSync(path.join(fontDir(pkg), file));
  const upm = font.unitsPerEm;
  const widths = {};
  let total = 0;
  let n = 0;
  for (const ch of chars) {
    const run = font.layout(ch);
    const adv = run.glyphs.reduce((s, g) => s + g.advanceWidth, 0);
    if (run.glyphs.every((g) => g.id === 0)) continue;
    widths[ch] = Math.round((adv / upm) * 1000);
    if (/[a-z]/.test(ch)) { total += widths[ch]; n++; }
  }
  out[key] = {
    family: font.familyName,
    ascent: Math.round((font.ascent / upm) * 1000),
    descent: Math.round((Math.abs(font.descent) / upm) * 1000),
    capHeight: Math.round((font.capHeight / upm) * 1000),
    fallback: Math.round((total / n) * 1.1),
    chars: Object.keys(widths).join(""),
    widths: Object.values(widths),
  };
}

const header = "// AUTO-GENERATED by scripts/gen-font-metrics.mjs — do not edit by hand.\n// Advance widths are in 1/1000 em.\n";
writeFileSync(
  new URL("../src/carousel/fontMetrics.generated.ts", import.meta.url),
  header + "export const FONT_METRICS_RAW = " + JSON.stringify(out) + " as const;\n",
);
console.log("Wrote metrics for", Object.keys(out).join(", "));
